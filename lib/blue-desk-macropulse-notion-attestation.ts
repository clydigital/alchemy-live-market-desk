import type {MacroPulseDigest} from "./blue-desk-macropulse-brief.ts";

/**
 * Optional, separately credentialled Notion SOURCE attestation for an
 * externally prepared, review-only MacroPulse digest. This proves only the
 * original Notion page's parent, ID, page creation clock, Pulse ID and cited
 * source-link presence. It does NOT verify the underlying market claims.
 *
 * No browser or ChatGPT OAuth credential is accepted. No canonical writer.
 */
const NOTION_ROOT="3ea519b6-7a94-8161-ba4d-ec8f97ebf658";
const NOTION_API="https://api.notion.com/v1";
const ID=/^[0-9a-f]{8}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{12}$/i;
type Json=Record<string,unknown>;
const obj=(v:unknown):Json=>v!==null&&typeof v==="object"&&!Array.isArray(v)?v as Json:{};
const list=(v:unknown):Json[]=>Array.isArray(v)?v.map(obj):[];
const id=(v:unknown)=>typeof v==="string"&&ID.test(v)?v.replaceAll("-","").toLowerCase():null;
const https=(v:unknown):string|null=>{
 if(typeof v!=="string")return null;
 try{
  const u=new URL(v);
  return u.protocol==="https:"&&!u.username&&!u.password?u.href:null;
 }catch{return null;}
};
export type SourceProof={sourceCreatedAt:string;sourceLastEditedAt:string;retrievedAt:string};

/** Only call from the already bearer-protected, private-host ingestion route. */
export async function attestMacroPulseNotionSource(
 digest:MacroPulseDigest,
 token:string,
 fetcher:typeof fetch=fetch,
 clock:()=>Date=()=>new Date(),
):Promise<SourceProof|null>{
 if(!token||token.trim()!==token||token.length<24)return null;
 const pulseDay=digest.sourcePulseId.slice(0,10);
 if(!/^20\d\d-\d\d-\d\d$/.test(pulseDay))return null;
 const api=async(path:string):Promise<Json>=>{
  const controller=new AbortController();
  const timeout=setTimeout(()=>controller.abort(),3500);
  try{
   const res=await fetcher(NOTION_API+path,{
    method:"GET",cache:"no-store",signal:controller.signal,
    headers:{"Authorization":"Bearer "+token,"Notion-Version":"2025-09-03"},
   });
   if(!res.ok)throw Error("notion_source_unavailable");
   return obj(await res.json());
  }finally{clearTimeout(timeout);}
 };
 // Page and parent IDs are generated by this server, never URL-supplied.
 const page=await api("/pages/"+digest.sourcePageId);
 if(id(page.id)!==id(digest.sourcePageId)||page.archived===true||
    page.in_trash===true)return null;
 const archiveId=id(obj(page.parent).page_id);
 if(!archiveId)return null;
 const archive=await api("/pages/"+archiveId);
 if(id(archive.id)!==archiveId||archive.archived===true||
    archive.in_trash===true||id(obj(archive.parent).page_id)!==id(NOTION_ROOT))
  return null;
 const titleProp=obj(obj(archive.properties).title);
 const title=list(titleProp.title).map(x=>String(x.plain_text||"")).join("");
 if(title!==pulseDay+" — MacroPulse")return null;
 const created=Date.parse(String(page.created_time||""));
 const edited=Date.parse(String(page.last_edited_time||""));
 const t=clock().getTime();
 if(!Number.isFinite(t)||!Number.isFinite(created)||!Number.isFinite(edited)||
    created>t||edited>t||edited<created||created<t-7*86400000)return null;
 // Never treat the declared scheduled slot as a publication timestamp.
 // created_time is a native Notion PAGE-CREATION proxy, not an independently
 // observed publishing event.
 const linkSet=new Set<string>();
 let text="";
 let cursor:string|undefined;
 let complete=false;
 for(let pass=0;pass<4;pass++){
  const query="/blocks/"+digest.sourcePageId+"/children?page_size=100"+
    (cursor?"&start_cursor="+encodeURIComponent(cursor):"");
  const result=await api(query);
  const blocks=list(result.results);
  for(const block of blocks){
   const content=obj(block[String(block.type||"")]);
   const rich=list(content.rich_text);
   for(const span of rich){
    const value=String(span.plain_text||obj(span.text).content||"");
    text+=value.slice(0,6000)+"\n";
    for(const raw of [span.href,obj(obj(span.text).link).url]){
     const u=https(raw);if(u)linkSet.add(u);
    }
    for(const m of value.matchAll(/https:\/\/[^\s<>"'`]+/g)){
     const u=https(m[0].replace(/[).,;!?\]}]+$/g,""));
     if(u)linkSet.add(u);
    }
   }
  }
  if(text.length>200000)return null;
  if(result.has_more!==true){complete=true;break;}
  if(typeof result.next_cursor!=="string"||result.next_cursor.length>500)return null;
  cursor=result.next_cursor;
 }
 if(!complete||!text.includes(digest.sourcePulseId))return null;
 if(!digest.sourceLinks.every(link=>linkSet.has(new URL(link.url).href)))return null;
 // Capture retrieval AFTER all bounded Notion block reads, not before them.
 // Combined worst-case request timeout remains below the receiver's 30s cap.
 const retrieved=clock().getTime();
 if(!Number.isFinite(retrieved)||retrieved<t||retrieved>t+30000)return null;
 return {sourceCreatedAt:new Date(created).toISOString(),
  sourceLastEditedAt:new Date(edited).toISOString(),
  retrievedAt:new Date(retrieved).toISOString()};
}
